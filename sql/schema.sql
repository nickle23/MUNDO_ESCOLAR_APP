/* Mundo Escolar - SQL Server 2022 schema
   Ejecutar en SSMS. Crea BD y tablas base para migrar desde Google Sheets.
*/

IF DB_ID(N'MUNDO_ESCOLAR') IS NULL
BEGIN
  CREATE DATABASE MUNDO_ESCOLAR;
END
GO

USE MUNDO_ESCOLAR;
GO

/* CONFIG */
IF OBJECT_ID('dbo.CONFIG', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.CONFIG (
    CLAVE NVARCHAR(100) NOT NULL PRIMARY KEY,
    VALOR NVARCHAR(MAX) NULL,
    DESCRIPCION NVARCHAR(500) NULL,
    ACTUALIZADO_EN DATETIME2 NOT NULL CONSTRAINT DF_CONFIG_ACT DEFAULT SYSDATETIME()
  );
END
GO

/* USUARIOS */
IF OBJECT_ID('dbo.USUARIOS', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.USUARIOS (
    ID_USUARIO NVARCHAR(50) NOT NULL PRIMARY KEY,
    NOMBRE NVARCHAR(150) NOT NULL,
    CONDUCTOR_HOJA NVARCHAR(150) NULL,
    PIN NVARCHAR(50) NOT NULL,
    ACTIVO BIT NOT NULL CONSTRAINT DF_USUARIOS_ACTIVO DEFAULT 1,
    ROL NVARCHAR(30) NOT NULL CONSTRAINT DF_USUARIOS_ROL DEFAULT 'REPARTIDOR',
    NOTAS NVARCHAR(500) NULL,
    PUEDE_COBRAR_DEUDAS BIT NOT NULL CONSTRAINT DF_USUARIOS_PCD DEFAULT 0,
    CREADO_EN DATETIME2 NOT NULL CONSTRAINT DF_USUARIOS_CREADO DEFAULT SYSDATETIME(),
    ACTUALIZADO_EN DATETIME2 NOT NULL CONSTRAINT DF_USUARIOS_ACT DEFAULT SYSDATETIME()
  );
  CREATE INDEX IX_USUARIOS_PIN ON dbo.USUARIOS(PIN, ACTIVO);
END
GO

/* CLIENTES */
IF OBJECT_ID('dbo.CLIENTES', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.CLIENTES (
    ID_CLIENTE NVARCHAR(50) NOT NULL PRIMARY KEY,
    NOMBRE NVARCHAR(200) NOT NULL,
    DIRECCION NVARCHAR(300) NULL,
    ZONA NVARCHAR(150) NULL,
    TELEFONO NVARCHAR(50) NULL,
    ACTIVO BIT NOT NULL CONSTRAINT DF_CLIENTES_ACTIVO DEFAULT 1,
    SALDO_PENDIENTE DECIMAL(12,2) NOT NULL CONSTRAINT DF_CLIENTES_SALDO DEFAULT 0,
    FECHA_ALTA DATE NULL,
    NOTAS NVARCHAR(500) NULL,
    CREADO_EN DATETIME2 NOT NULL CONSTRAINT DF_CLIENTES_CREADO DEFAULT SYSDATETIME(),
    ACTUALIZADO_EN DATETIME2 NOT NULL CONSTRAINT DF_CLIENTES_ACT DEFAULT SYSDATETIME()
  );
  CREATE INDEX IX_CLIENTES_NOMBRE ON dbo.CLIENTES(NOMBRE);
END
GO

/* INDICE_RUTAS */
IF OBJECT_ID('dbo.INDICE_RUTAS', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.INDICE_RUTAS (
    ID_RUTA NVARCHAR(100) NOT NULL PRIMARY KEY,
    FECHA DATE NOT NULL,
    CONDUCTOR NVARCHAR(150) NULL,
    ID_USUARIO NVARCHAR(50) NULL,
    SPREADSHEET_ID NVARCHAR(200) NULL, -- legado Sheets
    SPREADSHEET_URL NVARCHAR(500) NULL, -- legado Sheets
    HOJA NVARCHAR(150) NULL, -- legado/nombre ruta
    ESTADO NVARCHAR(30) NOT NULL CONSTRAINT DF_RUTAS_ESTADO DEFAULT 'ABIERTA',
    TOTAL_ENTREGAS INT NULL,
    CREADO_EN DATETIME2 NOT NULL CONSTRAINT DF_RUTAS_CREADO DEFAULT SYSDATETIME(),
    ACTUALIZADO_EN DATETIME2 NOT NULL CONSTRAINT DF_RUTAS_ACT DEFAULT SYSDATETIME(),
    CONSTRAINT FK_RUTAS_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES dbo.USUARIOS(ID_USUARIO)
  );
  CREATE INDEX IX_RUTAS_FECHA_USUARIO ON dbo.INDICE_RUTAS(FECHA, ID_USUARIO, ESTADO);
  CREATE INDEX IX_RUTAS_CONDUCTOR ON dbo.INDICE_RUTAS(FECHA, CONDUCTOR, ESTADO);
END
GO

/* ENTREGAS - reemplaza filas de hoja de ruta */
IF OBJECT_ID('dbo.ENTREGAS', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.ENTREGAS (
    ID_ENTREGA NVARCHAR(100) NOT NULL PRIMARY KEY,
    ID_RUTA NVARCHAR(100) NOT NULL,
    ROW_NUM INT NULL,
    DIRECCION NVARCHAR(300) NULL,
    CLIENTE NVARCHAR(200) NULL,
    ID_CLIENTE NVARCHAR(50) NULL,
    BO NVARCHAR(100) NULL,
    A1 NVARCHAR(100) NULL,
    A2 NVARCHAR(100) NULL,
    A3 NVARCHAR(100) NULL,
    TOT_B DECIMAL(12,2) NOT NULL CONSTRAINT DF_ENT_TOTB DEFAULT 0,
    TOT_MONT DECIMAL(12,2) NOT NULL CONSTRAINT DF_ENT_TOTM DEFAULT 0,
    MONTO_COBRAR DECIMAL(12,2) NOT NULL CONSTRAINT DF_ENT_MCOBRAR DEFAULT 0,
    VEND NVARCHAR(100) NULL,
    OBSERVACION NVARCHAR(MAX) NULL,
    EFECTIVO DECIMAL(12,2) NOT NULL CONSTRAINT DF_ENT_EF DEFAULT 0,
    YAPE DECIMAL(12,2) NOT NULL CONSTRAINT DF_ENT_YA DEFAULT 0,
    TRANSFERENCIA DECIMAL(12,2) NOT NULL CONSTRAINT DF_ENT_TR DEFAULT 0,
    TOTAL_PAGADO_HOY DECIMAL(12,2) NOT NULL CONSTRAINT DF_ENT_TPH DEFAULT 0,
    SALDO_ENTREGA_HOY DECIMAL(12,2) NOT NULL CONSTRAINT DF_ENT_SALDO DEFAULT 0,
    DEUDA_GENERADA_HOY DECIMAL(12,2) NOT NULL CONSTRAINT DF_ENT_DGH DEFAULT 0,
    VENCE_DEUDA DATE NULL,
    COBRO_DEUDA_ANTERIOR DECIMAL(12,2) NOT NULL CONSTRAINT DF_ENT_CDA DEFAULT 0,
    COBRO_DEUDA_EFECTIVO DECIMAL(12,2) NOT NULL CONSTRAINT DF_ENT_CDE DEFAULT 0,
    COBRO_DEUDA_YAPE DECIMAL(12,2) NOT NULL CONSTRAINT DF_ENT_CDY DEFAULT 0,
    COBRO_DEUDA_TRANSFERENCIA DECIMAL(12,2) NOT NULL CONSTRAINT DF_ENT_CDT DEFAULT 0,
    DETALLE_COBRO_DEUDA NVARCHAR(MAX) NULL,
    ESTADO_ENTREGA NVARCHAR(30) NOT NULL CONSTRAINT DF_ENT_ESTADO DEFAULT 'PENDIENTE',
    ID_DEUDA_GENERADA NVARCHAR(100) NULL,
    ULTIMA_EDICION DATETIME2 NULL,
    EDITADO_POR NVARCHAR(150) NULL,
    CREADO_EN DATETIME2 NOT NULL CONSTRAINT DF_ENT_CREADO DEFAULT SYSDATETIME(),
    ACTUALIZADO_EN DATETIME2 NOT NULL CONSTRAINT DF_ENT_ACT DEFAULT SYSDATETIME(),
    CONSTRAINT FK_ENTREGAS_RUTA FOREIGN KEY (ID_RUTA) REFERENCES dbo.INDICE_RUTAS(ID_RUTA),
    CONSTRAINT FK_ENTREGAS_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES dbo.CLIENTES(ID_CLIENTE)
  );
  CREATE INDEX IX_ENTREGAS_RUTA ON dbo.ENTREGAS(ID_RUTA, ROW_NUM);
  CREATE INDEX IX_ENTREGAS_CLIENTE ON dbo.ENTREGAS(ID_CLIENTE);
END
GO

/* DEUDAS */
IF OBJECT_ID('dbo.DEUDAS', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.DEUDAS (
    ID_DEUDA NVARCHAR(100) NOT NULL PRIMARY KEY,
    ID_CLIENTE NVARCHAR(50) NOT NULL,
    CLIENTE_NOMBRE NVARCHAR(200) NULL,
    FECHA_ORIGEN DATE NULL,
    ID_RUTA_ORIGEN NVARCHAR(100) NULL,
    ID_ENTREGA_ORIGEN NVARCHAR(100) NULL,
    MONTO_ORIGINAL DECIMAL(12,2) NOT NULL CONSTRAINT DF_DEU_MO DEFAULT 0,
    SALDO_PENDIENTE DECIMAL(12,2) NOT NULL CONSTRAINT DF_DEU_SALDO DEFAULT 0,
    FECHA_VENCIMIENTO DATE NULL,
    ESTADO NVARCHAR(30) NOT NULL CONSTRAINT DF_DEU_ESTADO DEFAULT 'PENDIENTE',
    OBSERVACION NVARCHAR(MAX) NULL,
    CREADO_POR NVARCHAR(150) NULL,
    CREADO_EN DATETIME2 NOT NULL CONSTRAINT DF_DEU_CREADO DEFAULT SYSDATETIME(),
    ACTUALIZADO_EN DATETIME2 NOT NULL CONSTRAINT DF_DEU_ACT DEFAULT SYSDATETIME(),
    CONSTRAINT FK_DEUDAS_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES dbo.CLIENTES(ID_CLIENTE)
  );
  CREATE INDEX IX_DEUDAS_CLIENTE ON dbo.DEUDAS(ID_CLIENTE, ESTADO, FECHA_VENCIMIENTO);
END
GO

/* MOVIMIENTOS */
IF OBJECT_ID('dbo.MOVIMIENTOS', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.MOVIMIENTOS (
    ID_MOVIMIENTO NVARCHAR(100) NOT NULL PRIMARY KEY,
    FECHA_HORA DATETIME2 NOT NULL CONSTRAINT DF_MOV_FH DEFAULT SYSDATETIME(),
    TIPO NVARCHAR(40) NOT NULL,
    ID_CLIENTE NVARCHAR(50) NULL,
    CLIENTE_NOMBRE NVARCHAR(200) NULL,
    ID_RUTA NVARCHAR(100) NULL,
    ID_ENTREGA NVARCHAR(100) NULL,
    ID_DEUDA NVARCHAR(100) NULL,
    MONTO_APLICADO DECIMAL(12,2) NOT NULL CONSTRAINT DF_MOV_MONTO DEFAULT 0,
    EFECTIVO DECIMAL(12,2) NOT NULL CONSTRAINT DF_MOV_EF DEFAULT 0,
    YAPE DECIMAL(12,2) NOT NULL CONSTRAINT DF_MOV_YA DEFAULT 0,
    TRANSFERENCIA DECIMAL(12,2) NOT NULL CONSTRAINT DF_MOV_TR DEFAULT 0,
    RESULTADO NVARCHAR(60) NULL,
    VENCIMIENTO_NUEVO DATE NULL,
    USUARIO NVARCHAR(150) NULL,
    OBSERVACION NVARCHAR(MAX) NULL
  );
  CREATE INDEX IX_MOV_CLIENTE ON dbo.MOVIMIENTOS(ID_CLIENTE, FECHA_HORA DESC);
  CREATE INDEX IX_MOV_RUTA ON dbo.MOVIMIENTOS(ID_RUTA, FECHA_HORA DESC);
END
GO

