-- Config básica
MERGE dbo.CONFIG AS t
USING (VALUES
  ('TIMEZONE', 'America/Lima', 'Zona horaria'),
  ('MODO', 'SQL_SERVER_LOCAL', 'Modo actual del sistema')
) AS s(CLAVE, VALOR, DESCRIPCION)
ON t.CLAVE = s.CLAVE
WHEN MATCHED THEN UPDATE SET VALOR=s.VALOR, DESCRIPCION=s.DESCRIPCION, ACTUALIZADO_EN=SYSDATETIME()
WHEN NOT MATCHED THEN INSERT (CLAVE, VALOR, DESCRIPCION) VALUES (s.CLAVE, s.VALOR, s.DESCRIPCION);

-- Usuarios de ejemplo (CAMBIAR PINES)
MERGE dbo.USUARIOS AS t
USING (VALUES
  ('USR001', 'JONATAN', 'JONATAN', '1234', 1, 'REPARTIDOR', 'Cambiar PIN', 0),
  ('USR002', 'NIXON',   'NIXON',   '2345', 1, 'REPARTIDOR', 'Cambiar PIN', 0)
) AS s(ID_USUARIO,NOMBRE,CONDUCTOR_HOJA,PIN,ACTIVO,ROL,NOTAS,PUEDE_COBRAR_DEUDAS)
ON t.ID_USUARIO = s.ID_USUARIO
WHEN MATCHED THEN UPDATE SET NOMBRE=s.NOMBRE, CONDUCTOR_HOJA=s.CONDUCTOR_HOJA, PIN=s.PIN, ACTIVO=s.ACTIVO, ROL=s.ROL, NOTAS=s.NOTAS, PUEDE_COBRAR_DEUDAS=s.PUEDE_COBRAR_DEUDAS, ACTUALIZADO_EN=SYSDATETIME()
WHEN NOT MATCHED THEN INSERT (ID_USUARIO,NOMBRE,CONDUCTOR_HOJA,PIN,ACTIVO,ROL,NOTAS,PUEDE_COBRAR_DEUDAS)
VALUES (s.ID_USUARIO,s.NOMBRE,s.CONDUCTOR_HOJA,s.PIN,s.ACTIVO,s.ROL,s.NOTAS,s.PUEDE_COBRAR_DEUDAS);

